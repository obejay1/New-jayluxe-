export const getProductBySlug = (slug: string) =>
  products.find((p) => p.slug === slug);

export const getProductsByCategory = (categorySlug: string) =>
  products.filter((p) => p.categorySlug === categorySlug && p.status === "published");

export const getPublishedProducts = () =>
  products.filter((p) => p.status === "published");

export const getNewArrivals = () =>
  products.filter((p) => p.isNew || p.badge === "New In");

export const getBestSellers = () =>
  products.filter((p) => p.isBestSeller || p.badge === "Best Seller");

export const getFeatured = () => products.filter((p) => p.isFeatured);

export const getRelatedProducts = (product: Product, limit = 4) =>
  products.filter(
    (p) => p.categorySlug === product.categorySlug && p.id !== product.id && p.status === "published",
  ).slice(0, limit);